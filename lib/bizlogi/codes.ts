// Biz-Logi API の処理結果コード (仕様書 Ver.2.82 「5.2 処理結果コード」)。
//
// コード形式 XY-9999: X = S(正常) / E(エラー) / W(ワーニング)、
// Y = 0(正常) 1(リクエスト内容) 2(判定内容) 3(認証) 8(処理内容) 9(システム)。
// 運営画面では message をそのまま見せ、action で「誰が何を直すか」を出し分ける。

export type ResultSeverity = "success" | "warning" | "error"

/**
 * 対応の種別。
 *   input    … 予約データ (住所・日付・文字数など) を直して送り直す
 *   contract … 佐川/SGシステムとの契約・設定の問題。データを直しても通らない
 *   auth     … カスタマーID/パスワードの設定誤り
 *   wait     … 佐川側の処理待ち。時間を置いて再照会する
 *   system   … 佐川側の障害。SGシステムのサポートへ問い合わせる
 *   none     … 対応不要
 */
export type ResultAction = "input" | "contract" | "auth" | "wait" | "system" | "none"

export interface ResultCodeInfo {
  code: string
  severity: ResultSeverity
  message: string
  action: ResultAction
  /** 仕様書に載っていないコード (版数が上がった等)。 */
  unknown?: boolean
}

