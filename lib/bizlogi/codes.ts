// データを直しても通らないもの (契約・SGシステム側の設定)。
const CONTRACT_CODES = new Set([
  "E1-0003", "E1-0007", "E1-0014", "E1-0066", "E1-0093", "E1-0094", "E1-0095", "E1-0096",
  "E1-0207", "E1-0212", "E1-0219", "E1-0220", "E2-0036",
])
const WAIT_CODES = new Set(["E2-0006"])

function actionFor(code: string, severity: ResultSeverity): ResultAction {
  if (severity !== "error") return "none"
  if (CONTRACT_CODES.has(code)) return "contract"
  if (WAIT_CODES.has(code)) return "wait"
  if (code.startsWith("E3-")) return "auth"
  if (code.startsWith("E9-") || code === "E8-0002" || code === "E8-0003") return "system"
  // E8-0001 は「明細のどれかがエラー」の総括コード。原因は明細側の結果コードを見る。
  return "input"
}

export function describeResultCode(code: string): ResultCodeInfo {
  const c = code.trim()
  const severity: ResultSeverity = c.startsWith("S") ? "success" : c.startsWith("W") ? "warning" : "error"
  const message = MESSAGES[c]
  if (!message) {
    return { code: c, severity, message: `未定義の処理結果コード (${c})`, action: actionFor(c, severity), unknown: true }
  }
  return { code: c, severity, message, action: actionFor(c, severity) }
}

export function isSuccess(code: string): boolean {
  return code.trim().startsWith("S")
}

export function isError(code: string): boolean {
  const c = code.trim()
  return c !== "" && !c.startsWith("S") && !c.startsWith("W")
}

export const KNOWN_RESULT_CODES: readonly string[] = Object.keys(MESSAGES)
